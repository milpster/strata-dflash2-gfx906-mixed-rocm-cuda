#!/usr/bin/env python3
"""
port-worklist.py - the semantic inventory of the two files this port did NOT carry.

`prefill.cpp` and `generate.cpp` are the fork's hottest files and upstream rewrote both. The fork's
difference against v0.2.18 is thousands of lines across hundreds of hunks, so they stayed upstream's
(PORT-NOTES.md). This tool turns that difference into a worklist someone can actually work from:
every fork-side hunk, labelled by the feature it belongs to, with the lines it adds, so the
reconciliation can be done one feature at a time against a boot instead of re-derived from a diff.

Read-only; writes one markdown file.

Usage: python3 tools-port/port-worklist.py [OUT]
"""
import re
import subprocess
import sys

FORK_REF = "564e1dbbea"
UP_REF = "v0.2.18"
FILES = [
    ("engine/src/program/generate.cpp", "src/program/generate.cpp"),
    ("engine/src/prefill/prefill.cpp", "src/prefill/prefill.cpp"),
]
REPO = "/mnt/srcds/Strata"

# Label order matters: the first hit wins, so the specific features come before the general ones.
LABELS = [
    ("expert helper", r"ExpertHelper|expert_helper|helper_frame|helper->|kBeginPrompt|image_q8_k|q8k"),
    ("CPU expert pool", r"PoolExpert|pool_expert|RamPool|ram_pool|BoundedDirect|bounded_direct"),
    ("per-card VRAM clamp", r"vram_guard|foresight|STRATA_FS_SLOTS|card_slots|cudaMemGetInfo"),
    ("DFlash2 drafter", r"[Dd]flash|tap_plan|tap_collect|Drafter"),
    ("conversation cache", r"[Cc]onversation|conv_cache|ConvCache|snapshot"),
    ("MTP / verify window", r"\bmtp|MTP|verify_batch|window_t"),
    ("speculative decode", r"[Ss]pec_|speculative|proposal|draft"),
    ("QSA attention", r"\bqsa|Qsa|QSA"),
    ("prompt kernels / MMQ", r"mmq|MMQ|moe_ws|moe_fused|prefill_fused|swiglu"),
    ("peer / split engine", r"peer_expert|[Pp]eer|split_lend|strata-split"),
    ("telemetry", r"telemetry|report|logit|stats"),
]


def show(ref, path):
    args = ["git", "-C", REPO, "show", f"{ref}:{path}"]
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "/mnt/srcds/Strata-wt-0218/PORT-WORKLIST-UNPORTED.md"
    lines = [
        "# The two files this port left as upstream's",
        "",
        "Generated by `tools-port/port-worklist.py` from a diff of the fork's file against upstream",
        "v0.2.18's. It is a worklist, not a patch: nothing here was applied. Every hunk below is a piece",
        "of the fork's behaviour that upstream's file does not have, grouped by the feature it belongs to.",
        "",
        "Working order suggestion: do the `expert helper`, `CPU expert pool` and `per-card VRAM clamp`",
        "groups first (they are what the mixed-GPU serving lane needs), one group at a time, and after each",
        "group boot the engine and compare a fixed prompt's output against the fork's build before the next.",
        "",
    ]
    for up_path, fork_path in FILES:
        up = show(UP_REF, up_path)
        fork = show(FORK_REF, fork_path)
        up_p, fork_p = "/tmp/up.cpp", "/tmp/fork.cpp"
        open(up_p, "w").write(up)
        open(fork_p, "w").write(fork)
        d = subprocess.run(["diff", "-u", up_p, fork_p], capture_output=True, text=True).stdout.splitlines()
        hunks, cur = [], None
        for ln in d:
            if ln.startswith("@@"):
                if cur:
                    hunks.append(cur)
                cur = {"hdr": ln, "add": [], "del": []}
            elif cur is not None and ln.startswith("+") and not ln.startswith("+++"):
                cur["add"].append(ln[1:])
            elif cur is not None and ln.startswith("-") and not ln.startswith("---"):
                cur["del"].append(ln[1:])
        if cur:
            hunks.append(cur)

        def label(h):
            body = "\n".join(h["add"] + h["del"])
            for name, pat in LABELS:
                if re.search(pat, body):
                    return name
            return "other"

        counts = {}
        for h in hunks:
            counts.setdefault(label(h), []).append(h)
        adds = sum(len(h["add"]) for h in hunks)
        dels = sum(len(h["del"]) for h in hunks)
        lines += [
            "## `%s`" % up_path,
            "",
            "- fork's file: `%s` (fork `%s`), upstream's: `%s` (`%s`)" % (fork_path, FORK_REF[:10], up_path, UP_REF),
            "- %d hunks, %d added lines, %d removed lines relative to upstream" % (len(hunks), adds, dels),
            "- upstream's file is %d lines; the fork's is %d" % (len(up.splitlines()), len(fork.splitlines())),
            "",
            "| feature | hunks | added | removed |",
            "| --- | --- | --- | --- |",
        ]
        for feat in sorted(counts, key=lambda f: -len(counts[f])):
            hs = counts[feat]
            lines.append("| %s | %d | %d | %d |"
                         % (feat, len(hs), sum(len(h["add"]) for h in hs), sum(len(h["del"]) for h in hs)))
        lines.append("")
        # The lane's own groups in full; the rest by size only, so the file stays readable.
        for feat in sorted(counts, key=lambda f: -len(counts[f])):
            hs = counts[feat]
            if feat not in ("expert helper", "CPU expert pool", "per-card VRAM clamp"):
                continue
            lines += ["### %s / `%s` - %d hunks" % (up_path.split("/")[-1], feat, len(hs)), ""]
            for i, h in enumerate(hs, 1):
                first = next((x for x in h["add"] if x.strip()), "")
                lines += [
                    "**%d.** `%s` (+%d/-%d) first added line: `%s`"
                    % (i, h["hdr"], len(h["add"]), len(h["del"]), first.strip()[:110]),
                    "",
                    "```cpp",
                ]
                lines += h["add"][:60]
                if len(h["add"]) > 60:
                    lines.append("// ... %d more added lines in this hunk" % (len(h["add"]) - 60))
                lines += ["```", ""]
    open(out_path, "w").write("\n".join(lines) + "\n")
    print("wrote %s (%d lines)" % (out_path, len(lines)))


main()
